function applyPageTranslations(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        if (!element.dataset.i18nOriginal) {
            element.dataset.i18nOriginal = element.innerHTML;
        }

        element.innerHTML = lang === 'ru'
            ? element.dataset.i18nOriginal
            : pageTranslations[lang][element.dataset.i18n] || element.dataset.i18nOriginal;
    });

    document.documentElement.lang = lang === 'ua' ? 'uk' : lang;
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('selectedLang', lang);

    const t = translations[lang];

    // 1. Тексты главной страницы
    const hTitle = document.getElementById('hero-title');
    const hSub = document.getElementById('hero-sub');
    const hDesc = document.getElementById('hero-desc');
    const gTitle = document.getElementById('grid-title');
    const headerTitle = document.getElementById('home-header-title');
    const headerSubtitle = document.getElementById('home-header-subtitle');
    const qBtn = document.getElementById('quiz-nav-btn');
    const bHome = document.getElementById('back-home-link');
    const contactInput = document.getElementById('contact');
    const problemInput = document.getElementById('problem-desc');
    const feedbackTitle = document.getElementById('feedback-title');
    const feedbackDescription = document.getElementById('feedback-description');
    const contactLabel = document.getElementById('contact-label');
    const problemLabel = document.getElementById('problem-label');
    const submitLabel = document.getElementById('feedback-submit');

    if (headerTitle) {
        document.title = t.documentTitle;
        headerTitle.textContent = t.headerTitle;
    }
    if (headerSubtitle) headerSubtitle.textContent = t.headerSubtitle;
    if (hTitle) hTitle.textContent = t.heroTitle;
    if (hSub) hSub.innerHTML = t.heroSub;
    if (hDesc) hDesc.textContent = t.heroDesc;
    if (gTitle) gTitle.textContent = t.gridTitle;
    if (qBtn) qBtn.textContent = t.quizNav;
    if (bHome) bHome.textContent = t.backHome;
    if (contactInput) contactInput.placeholder = t.contactPlaceholder;
    if (problemInput) problemInput.placeholder = t.problemPlaceholder;
    if (feedbackTitle) feedbackTitle.textContent = t.feedbackTitle;
    if (feedbackDescription) feedbackDescription.textContent = t.feedbackDescription;
    if (contactLabel) contactLabel.textContent = t.contactLabel;
    if (problemLabel) problemLabel.textContent = t.problemLabel;
    if (submitLabel) submitLabel.textContent = t.submitLabel;

    // 2. Карточки проблем
    const cardKeys = ['overheat', 'exhaust', 'electrical', 'transmission', 'settings'];
    const cards = document.querySelectorAll('.problem-card');
    cards.forEach((card, index) => {
        const key = cardKeys[index];
        if (key && t.cards[key]) {
            const data = t.cards[key];
            const tag = card.querySelector('.card-tag');
            const title = card.querySelector('.card-title');
            const desc = card.querySelector('.card-desc');
            const btn = card.querySelector('.card-arrow');

            if (tag) tag.textContent = data.tag;
            if (title) title.textContent = data.title;
            if (desc) desc.textContent = data.desc;
            if (btn) btn.textContent = data.btn;
        }
    });

    // 3. Тексты страницы overheat.html (если мы на ней)
    const ohTitle = document.getElementById('oh-title');
    const ohReasonTitle = document.getElementById('oh-reason-title');
    if (ohTitle && t.overheatPage) ohTitle.textContent = t.overheatPage.title;
    if (ohReasonTitle && t.overheatPage) ohReasonTitle.textContent = t.overheatPage.reasonTitle;
    
    const ohReasons = document.querySelectorAll('.oh-reason-item');
    if (ohReasons.length && t.overheatPage) {
        ohReasons.forEach((item, idx) => {
            if (t.overheatPage.reasons[idx]) item.textContent = t.overheatPage.reasons[idx];
        });
    }

    applyPageTranslations(lang);

    // Подсветка кнопок
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('selectedLang') || 'ru';
    setLanguage(savedLang);
});